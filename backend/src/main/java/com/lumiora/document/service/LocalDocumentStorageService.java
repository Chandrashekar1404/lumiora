
package com.lumiora.document.service;

import org.springframework.core.io.Resource;
import org.springframework.core.io.UrlResource;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Locale;
import java.util.UUID;

@Service
public class LocalDocumentStorageService
        implements DocumentStorageService {

    private final Path root;

    public LocalDocumentStorageService(Path documentStoragePath)
            throws IOException {
        this.root = documentStoragePath.toAbsolutePath().normalize();
        Files.createDirectories(this.root);
    }

    @Override
    public String store(MultipartFile file) throws IOException {
        String extension = getSafeExtension(file.getOriginalFilename());
        String storageKey = UUID.randomUUID() + extension;
        Path destination = resolveSafePath(storageKey);

        try (InputStream input = file.getInputStream()) {
            Files.copy(input, destination,
                    StandardCopyOption.REPLACE_EXISTING);
        }

        return storageKey;
    }

    @Override
    public Resource load(String storageKey) throws IOException {
        Path path = resolveSafePath(storageKey);

        if (!Files.isRegularFile(path)) {
            throw new IOException("Stored document was not found");
        }

        Resource resource = new UrlResource(path.toUri());

        if (!resource.exists() || !resource.isReadable()) {
            throw new IOException("Stored document is not readable");
        }

        return resource;
    }

    @Override
    public void delete(String storageKey) throws IOException {
        Files.deleteIfExists(resolveSafePath(storageKey));
    }

    private Path resolveSafePath(String storageKey) throws IOException {
        // Keys are generated by this service and must be simple UUID filenames.
        if (storageKey == null
                || !storageKey.matches(
                    "^[0-9a-fA-F-]{36}\\.(pdf|jpg|jpeg|png)$")) {
            throw new IOException("Invalid document storage key");
        }

        Path resolved = root.resolve(storageKey).normalize();

        if (!resolved.startsWith(root)) {
            throw new IOException("Invalid document path");
        }

        return resolved;
    }

    private String getSafeExtension(String originalFilename)
            throws IOException {
        if (originalFilename == null || originalFilename.isBlank()) {
            throw new IOException("Filename is required");
        }

        String filename = originalFilename.replace('\\', '/');
        filename = filename.substring(filename.lastIndexOf('/') + 1);

        int dot = filename.lastIndexOf('.');
        if (dot < 0 || dot == filename.length() - 1) {
            throw new IOException("File extension is required");
        }

        String extension = filename.substring(dot).toLowerCase(Locale.ROOT);

        if (!extension.matches("\\.(pdf|jpg|jpeg|png)")) {
            throw new IOException("Unsupported file extension");
        }

        return extension;
    }
}